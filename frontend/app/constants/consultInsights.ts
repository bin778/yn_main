export function getConsultLawyerForTopic(topic: string | undefined): ConsultInsightLawyer {
  if (topic === CONSULT_TOPICS.DRUNK_DRIVING || topic === CONSULT_TOPICS.REAL_ESTATE) {
    return LAWYER_YOO_YOUNG_KYU;
  }
  if (topic === CONSULT_TOPICS.FAMILY || topic === CONSULT_TOPICS.ECONOMIC_CRIME) {
    return LAWYER_KIM_HWAN_SOB;
  }
  if (topic === CONSULT_TOPICS.DRUG || topic === CONSULT_TOPICS.CORPORATE) {
    return LAWYER_HONG_KI_WOONG;
  }
  if (topic === CONSULT_TOPICS.SEXUAL_ASSAULT || topic === CONSULT_TOPICS.OTHER) {
    return LAWYER_KIM_SUN_HO;
  }
  return DEFAULT_CONSULT_LAWYER;
}

export function getConsultQuestionLawyer(questionId: ConsultQuestionId, topic?: string): ConsultInsightLawyer {
  if (questionId === 'topic') return DEFAULT_CONSULT_LAWYER;
  return getConsultLawyerForTopic(topic);
}

export function getConsultInsight(
  questionId: ConsultQuestionId,
  option: string,
  topic?: string,
): ConsultInsight | null {
  const messages = CONSULT_INSIGHT_MESSAGES[questionId];
  if (!messages) return null;

  const message = messages[option] ?? messages[INSIGHT_FALLBACK_KEY];
  if (!message) return null;

  return {
    message,
    lawyer: getConsultLawyerForTopic(topic),
  };
}
